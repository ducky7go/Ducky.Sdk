namespace Ducky.Sdk.Lib.Tests.Runner;

/// <summary>
/// Task 5.2: ExtractLocalizationKeysLib reads the JsonData constant from a generated LKeys.*.metadata.g.cs
/// and writes lkeys.json. The golden is the baseline Ducky.TryHarmony lkeys.json.
/// </summary>
public class ExtractLocalizationKeysLibTests
{
    private string _root = null!;
    private string _projectDir = null!;
    private string _objDir = null!;
    private string _assetsDir = null!;

    [SetUp]
    public void SetUp()
    {
        _root = LibTestSupport.NewTempRoot("lkeys-extract");
        _projectDir = Path.Combine(_root, "Ducky TryHarmony");
        _objDir = Path.Combine(_projectDir, "obj");
        _assetsDir = Path.Combine(_projectDir, "assets");
        Directory.CreateDirectory(_objDir);
        Directory.CreateDirectory(_assetsDir);
    }

    [TearDown]
    public void TearDown() => LibTestSupport.DeleteTempRoot(_root);

    private BuildContext Context() => LibTestSupport.NewContext(
        _projectDir, modName: "Ducky.TryHarmony", assetsDir: _assetsDir);

    private static string GoldenLkeys => File.ReadAllText(LibTestSupport.Golden("TryHarmony", "lkeys.json"));

    /// <summary>Writes a generated metadata file whose JsonData verbatim string holds <paramref name="json"/>.</summary>
    private string WriteMetadata(string json)
    {
        var escaped = json.Replace("\"", "\"\"");
        var path = Path.Combine(_objDir, "Debug", "netstandard2.1", "LKeys.Ducky.TryHarmony.metadata.g.cs");
        var source =
            "// <auto-generated/>\n" +
            "namespace Ducky.TryHarmony\n" +
            "{\n" +
            "    internal static class LKeys\n" +
            "    {\n" +
            "        internal const string JsonData = @\"" + escaped + "\";\n" +
            "    }\n" +
            "}\n";
        LibTestSupport.WriteText(path, source);
        return path;
    }

    [Test]
    public void Execute_WritesLkeysJsonMatchingBaselineGolden()
    {
        WriteMetadata(GoldenLkeys);
        var context = Context();

        var (exit, output, _) = LibTestSupport.Capture(() => ExtractLocalizationKeysLib.Execute(context));

        exit.ShouldBe(0);
        File.ReadAllText(Path.Combine(_assetsDir, "lkeys.json")).ShouldBe(GoldenLkeys);
        output.ShouldContain("Keys Count: 2");
    }

    [Test]
    public void Execute_ReportsZeroKeysAndWritesNothingWhenProjectHasNoLkeysMetadata()
    {
        var context = Context();

        var (exit, output, _) = LibTestSupport.Capture(() => ExtractLocalizationKeysLib.Execute(context));

        exit.ShouldBe(0);
        output.ShouldContain("Keys Count: 0");
        File.Exists(Path.Combine(_assetsDir, "lkeys.json")).ShouldBeFalse();
    }

    [Test]
    public void Execute_FailsWithoutWritingWhenJsonDataConstantIsMissing()
    {
        var path = Path.Combine(_objDir, "Debug", "LKeys.Ducky.TryHarmony.metadata.g.cs");
        LibTestSupport.WriteText(path, "namespace Ducky.TryHarmony { internal static class LKeys { } }\n");
        var context = Context();

        var (exit, output, error) = LibTestSupport.Capture(() => ExtractLocalizationKeysLib.Execute(context));

        // Not 0 (success) and not SkipExitCode: the runner treats both as a failed step.
        exit.ShouldNotBe(0);
        exit.ShouldNotBe(BuildScriptGlobals.SkipExitCode);
        output.ShouldContain("Error: JsonData constant not found");
        error.ShouldContain("Could not find JsonData constant");
        File.Exists(Path.Combine(_assetsDir, "lkeys.json")).ShouldBeFalse();
    }

    [Test]
    public void Execute_FailsWithoutWritingWhenObjDirectoryIsMissing()
    {
        var context = LibTestSupport.NewContext(
            _projectDir, modName: "Ducky.TryHarmony", assetsDir: _assetsDir,
            baseIntermediateOutputPath: Path.Combine(_root, "no obj") + "/");

        var (exit, output, _) = LibTestSupport.Capture(() => ExtractLocalizationKeysLib.Execute(context));

        exit.ShouldNotBe(0);
        exit.ShouldNotBe(BuildScriptGlobals.SkipExitCode);
        output.ShouldContain("Error: Object directory not found");
        File.Exists(Path.Combine(_assetsDir, "lkeys.json")).ShouldBeFalse();
    }

    [Test]
    public void Execute_WarnsAndStillWritesWhenExtractedContentIsNotJson()
    {
        WriteMetadata("not { json");
        var context = Context();

        var (_, output, _) = LibTestSupport.Capture(() => ExtractLocalizationKeysLib.Execute(context));

        output.ShouldContain("not valid JSON");
        File.ReadAllText(Path.Combine(_assetsDir, "lkeys.json")).ShouldBe("not { json");
    }
}
